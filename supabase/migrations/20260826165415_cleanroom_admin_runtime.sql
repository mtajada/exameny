begin;

-- Keep operational audit data outside every schema exposed by the Data API.
create schema if not exists private authorization postgres;

revoke all on schema private from public, anon, authenticated, service_role;

create table if not exists private.event_outbox (
  id bigint generated by default as identity primary key,
  event_type text not null check (btrim(event_type) <> ''),
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default clock_timestamp(),
  processed_at timestamptz
);

create index if not exists event_outbox_unprocessed_idx
  on private.event_outbox (created_at, id)
  where processed_at is null;

create table if not exists private.membership_alias_conflicts (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  membership_id bigint references public.academy_memberships(id) on delete set null,
  email_login text not null,
  email_membership text not null,
  request_id uuid not null,
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  detected_at timestamptz not null default clock_timestamp(),
  resolved_at timestamptz,
  resolver_id uuid references public.profiles(id) on delete set null,
  resolution_reason text,
  resolution_request_id uuid unique,
  constraint membership_alias_conflicts_login_email_check
    check (email_login = lower(btrim(email_login)) and position('@' in email_login) > 1),
  constraint membership_alias_conflicts_membership_email_check
    check (email_membership = lower(btrim(email_membership)) and position('@' in email_membership) > 1),
  constraint membership_alias_conflicts_request_key
    unique (email_login, email_membership, request_id)
);

create index if not exists membership_alias_conflicts_open_membership_idx
  on private.membership_alias_conflicts (membership_id, detected_at desc, id desc)
  where resolved_at is null;

create table if not exists private.membership_role_audit (
  id bigint generated by default as identity primary key,
  membership_id bigint references public.academy_memberships(id) on delete set null,
  academy_id bigint references public.academies(id) on delete set null,
  actor_user_id uuid references public.profiles(id) on delete set null,
  old_role text not null,
  new_role text not null,
  reason text,
  request_id uuid not null,
  cleaned_records jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default clock_timestamp(),
  constraint membership_role_audit_request_key unique (request_id)
);

alter table private.event_outbox enable row level security;
alter table private.membership_alias_conflicts enable row level security;
alter table private.membership_role_audit enable row level security;

revoke all privileges on all tables in schema private
  from public, anon, authenticated, service_role;
revoke all privileges on all sequences in schema private
  from public, anon, authenticated, service_role;
alter default privileges for role postgres in schema private
  revoke all on tables from public, anon, authenticated, service_role;
alter default privileges for role postgres in schema private
  revoke all on sequences from public, anon, authenticated, service_role;
alter default privileges for role postgres in schema private
  revoke execute on functions from public, anon, authenticated, service_role;

create or replace function private.assert_service_role()
returns void
language plpgsql
stable
security invoker
set search_path = ''
as $$
begin
  if coalesce(current_setting('role', true), '') <> 'service_role'
     and coalesce(auth.jwt() ->> 'role', '') <> 'service_role' then
    raise exception using message = 'SERVICE_ROLE_REQUIRED';
  end if;
end;
$$;

create or replace function private.assert_admin_actor(
  p_actor_user_id uuid,
  p_actor_academy_id bigint,
  p_actor_is_platform_admin boolean,
  p_target_academy_id bigint
)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform private.assert_service_role();

  if p_actor_user_id is null or p_target_academy_id is null then
    raise exception using message = 'ACTOR_CONTEXT_REQUIRED';
  end if;

  if p_actor_is_platform_admin then
    if not exists (
      select 1
      from public.profiles p
      where p.id = p_actor_user_id
        and p.role in ('platform_owner', 'super_admin')
    ) then
      raise exception using message = 'ACTOR_CONTEXT_REQUIRED';
    end if;
    return;
  end if;

  if p_actor_academy_id is null or p_actor_academy_id <> p_target_academy_id then
    raise exception using message = 'ROLE_SCOPE_CONFLICT';
  end if;

  if not exists (
    select 1
    from public.academy_memberships am
    where am.user_id = p_actor_user_id
      and am.academy_id = p_actor_academy_id
      and am.role = 'academy_admin'
      and am.status = 'active'
  ) then
    raise exception using message = 'ACTOR_CONTEXT_REQUIRED';
  end if;
end;
$$;

