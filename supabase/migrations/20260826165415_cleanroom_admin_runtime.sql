create or replace function public.upsert_membership_alias_conflict(
  p_user_id uuid,
  p_membership_id bigint,
  p_email_login text,
  p_email_membership text,
  p_request_id uuid,
  p_payload jsonb default '{}'::jsonb
)
returns table (
  id bigint,
  user_id uuid,
  email_login text,
  email_membership text,
  membership_id bigint,
  request_id uuid,
  payload jsonb,
  detected_at timestamptz,
  resolved_at timestamptz,
  resolver_id uuid
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email_login text := lower(btrim(coalesce(p_email_login, '')));
  v_email_membership text := lower(btrim(coalesce(p_email_membership, '')));
begin
  perform private.assert_service_role();
  if position('@' in v_email_login) <= 1 or position('@' in v_email_membership) <= 1 then
    raise exception using message = 'ALIAS_EMAIL_INVALID';
  end if;
  if p_request_id is null then
    raise exception using message = 'REQUEST_ID_REQUIRED';
  end if;
  if p_user_id is not null and not exists (
    select 1 from public.profiles p where p.id = p_user_id
  ) then
    raise exception using message = 'ALIAS_USER_NOT_FOUND';
  end if;
  if p_membership_id is not null and not exists (
    select 1 from public.academy_memberships am where am.id = p_membership_id
  ) then
    raise exception using message = 'MEMBERSHIP_NOT_FOUND';
  end if;

  return query
  insert into private.membership_alias_conflicts (
    user_id,
    membership_id,
    email_login,
    email_membership,
    request_id,
    payload
  ) values (
    p_user_id,
    p_membership_id,
    v_email_login,
    v_email_membership,
    p_request_id,
    coalesce(p_payload, '{}'::jsonb)
  )
  on conflict on constraint membership_alias_conflicts_request_key do update set
    user_id = coalesce(excluded.user_id, private.membership_alias_conflicts.user_id),
    membership_id = coalesce(excluded.membership_id, private.membership_alias_conflicts.membership_id),
    payload = private.membership_alias_conflicts.payload || excluded.payload,
    resolved_at = null,
    resolver_id = null,
    resolution_reason = null,
    resolution_request_id = null
  returning
    private.membership_alias_conflicts.id,
    private.membership_alias_conflicts.user_id,
    private.membership_alias_conflicts.email_login,
    private.membership_alias_conflicts.email_membership,
    private.membership_alias_conflicts.membership_id,
    private.membership_alias_conflicts.request_id,
    private.membership_alias_conflicts.payload,
    private.membership_alias_conflicts.detected_at,
    private.membership_alias_conflicts.resolved_at,
    private.membership_alias_conflicts.resolver_id;
end;
$$;

