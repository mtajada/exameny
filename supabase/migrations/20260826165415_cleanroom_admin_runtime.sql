create or replace function public.admin_manage_membership(
  p_membership_id bigint,
  p_target_user_id uuid default null,
  p_email text default null,
  p_role text default null,
  p_subscription_start_date date default null,
  p_subscription_end_date date default null,
  p_clear_user boolean default false,
  p_delete_auth_user boolean default false,
  p_allow_active_clear boolean default false,
  p_status text default null,
  p_force_status_active boolean default false,
  p_request_id uuid default gen_random_uuid()
)
returns table (
  academy_id bigint,
  created_at timestamptz,
  email text,
  id bigint,
  metadata_payload jsonb,
  metadata_targets jsonb,
  request_id uuid,
  role text,
  should_refresh_session boolean,
  status text,
  subscription_end_date date,
  subscription_start_date date,
  updated_at timestamptz,
  user_id uuid
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_membership public.academy_memberships%rowtype;
  v_old_user_id uuid;
  v_old_metadata_payload jsonb;
  v_new_metadata_payload jsonb;
  v_metadata_targets jsonb := '[]'::jsonb;
  v_request_id uuid := coalesce(p_request_id, gen_random_uuid());
begin
  perform private.assert_service_role();
  select * into v_membership
  from public.academy_memberships am where am.id = p_membership_id for update;
  if v_membership.id is null then
    raise exception 'Not authorized';
  end if;
  if p_delete_auth_user then
    raise exception using message = 'AUTH_USER_DELETE_UNSUPPORTED';
  end if;
  if p_role is not null and p_role not in ('student', 'teacher', 'academy_admin') then
    raise exception 'Invalid role';
  end if;
  if p_status is not null and p_status not in ('awaiting_login', 'active', 'inactive') then
    raise exception 'Invalid status';
  end if;
  if p_clear_user and v_membership.status = 'active' and not p_allow_active_clear then
    raise exception 'Explicit active-clear approval is required';
  end if;

  v_old_user_id := v_membership.user_id;
  update public.academy_memberships am
  set user_id = case when p_clear_user then null else coalesce(p_target_user_id, am.user_id) end,
      email = coalesce(lower(btrim(p_email)), am.email),
      role = coalesce(p_role, am.role),
      status = case
        when p_clear_user then 'awaiting_login'
        when p_force_status_active then 'active'
        else coalesce(p_status, am.status)
      end,
      subscription_start_date = coalesce(p_subscription_start_date, am.subscription_start_date),
      subscription_end_date = coalesce(p_subscription_end_date, am.subscription_end_date)
  where am.id = p_membership_id
  returning * into v_membership;

  if v_old_user_id is not null then
    perform public.reconcile_active_academy_preference(v_old_user_id);
    select synced.metadata_payload into v_old_metadata_payload
    from public.sync_user_metadata(
      v_old_user_id,
      '[]'::jsonb,
      v_request_id
    ) synced;
    v_metadata_targets := v_metadata_targets || jsonb_build_array(
      jsonb_build_object(
        'user_id', v_old_user_id,
        'metadata_payload', v_old_metadata_payload,
        'should_refresh_session', true,
        'request_id', v_request_id
      )
    );
  end if;
  if v_membership.user_id is not null
     and v_membership.user_id is distinct from v_old_user_id then
    perform public.reconcile_active_academy_preference(v_membership.user_id);
    select synced.metadata_payload into v_new_metadata_payload
    from public.sync_user_metadata(
      v_membership.user_id,
      '[]'::jsonb,
      v_request_id
    ) synced;
    v_metadata_targets := v_metadata_targets || jsonb_build_array(
      jsonb_build_object(
        'user_id', v_membership.user_id,
        'metadata_payload', v_new_metadata_payload,
        'should_refresh_session', true,
        'request_id', v_request_id
      )
    );
  end if;

  academy_id := v_membership.academy_id;
  created_at := v_membership.created_at;
  email := v_membership.email;
  id := v_membership.id;
  metadata_payload := case
    when v_membership.user_id is null then v_old_metadata_payload
    when v_membership.user_id = v_old_user_id then v_old_metadata_payload
    else v_new_metadata_payload
  end;
  metadata_targets := v_metadata_targets;
  request_id := v_request_id;
  role := v_membership.role;
  should_refresh_session := jsonb_array_length(v_metadata_targets) > 0;
  status := v_membership.status;
  subscription_end_date := v_membership.subscription_end_date;
  subscription_start_date := v_membership.subscription_start_date;
  updated_at := v_membership.updated_at;
  user_id := v_membership.user_id;
  return next;
end;
$$;

