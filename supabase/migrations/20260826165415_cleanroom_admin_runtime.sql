create or replace function public.migrate_membership_role(
  p_actor_user_id uuid,
  p_actor_academy_id bigint,
  p_actor_is_platform_admin boolean,
  p_membership_id bigint,
  p_new_role text,
  p_reason text default null,
  p_request_id uuid default gen_random_uuid()
)
returns table (
  membership_id bigint,
  academy_id bigint,
  old_role text,
  new_role text,
  cleaned_records jsonb,
  metadata_payload jsonb,
  should_refresh_session boolean,
  request_id uuid
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_membership public.academy_memberships%rowtype;
  v_profile_email text;
  v_conflicting_role text;
  v_student_profiles integer := 0;
  v_class_memberships integer := 0;
  v_cleaned jsonb;
  v_metadata_payload jsonb := null;
  v_metadata_request_id uuid := null;
  v_existing_audit private.membership_role_audit%rowtype;
  v_request_id uuid := coalesce(p_request_id, gen_random_uuid());
begin
  perform private.assert_service_role();
  if p_membership_id is null then
    raise exception using message = 'MEMBERSHIP_NOT_FOUND';
  end if;
  if p_new_role not in ('student', 'teacher') then
    raise exception using message = 'ROLE_IMMUTABLE';
  end if;

  select * into v_existing_audit
  from private.membership_role_audit mra
  where mra.request_id = v_request_id;

  if v_existing_audit.id is not null then
    if v_existing_audit.membership_id is distinct from p_membership_id
       or v_existing_audit.actor_user_id is distinct from p_actor_user_id
       or v_existing_audit.new_role is distinct from p_new_role then
      raise exception using message = 'REQUEST_ID_REUSE';
    end if;

    perform private.assert_admin_actor(
      p_actor_user_id,
      p_actor_academy_id,
      coalesce(p_actor_is_platform_admin, false),
      v_existing_audit.academy_id
    );

    select * into v_membership
    from public.academy_memberships am
    where am.id = p_membership_id;
    if v_membership.id is null then
      raise exception using message = 'MEMBERSHIP_NOT_FOUND';
    end if;

    if v_membership.user_id is not null then
      select synced.metadata_payload, synced.request_id
      into v_metadata_payload, v_metadata_request_id
      from public.sync_user_metadata(
        v_membership.user_id,
        '[]'::jsonb,
        v_request_id
      ) synced;
    end if;

    membership_id := v_existing_audit.membership_id;
    academy_id := v_existing_audit.academy_id;
    old_role := v_existing_audit.old_role;
    new_role := v_existing_audit.new_role;
    cleaned_records := v_existing_audit.cleaned_records;
    metadata_payload := v_metadata_payload;
    should_refresh_session := v_membership.user_id is not null;
    request_id := v_request_id;
    return next;
    return;
  end if;

  select * into v_membership
  from public.academy_memberships am
  where am.id = p_membership_id
  for update;
  if v_membership.id is null then
    raise exception using message = 'MEMBERSHIP_NOT_FOUND';
  end if;

  perform private.assert_admin_actor(
    p_actor_user_id,
    p_actor_academy_id,
    coalesce(p_actor_is_platform_admin, false),
    v_membership.academy_id
  );

  if v_membership.role = 'academy_admin' then
    raise exception using message = 'ROLE_IMMUTABLE';
  end if;

  if v_membership.user_id is not null then
    if exists (
      select 1
      from public.profiles p
      where p.id = v_membership.user_id
        and p.role in ('platform_owner', 'super_admin')
    ) or exists (
      select 1
      from public.academy_memberships am
      where am.user_id = v_membership.user_id
        and am.role = 'academy_admin'
        and am.id <> v_membership.id
    ) then
      raise exception using message = 'ROLE_IMMUTABLE_CROSS_ACADEMY';
    end if;

    select p.email into v_profile_email
    from public.profiles p
    where p.id = v_membership.user_id;
    if v_profile_email is null or lower(btrim(v_profile_email)) <> v_membership.email then
      raise exception using
        message = 'MEMBERSHIP_OWNERSHIP_CONFLICT',
        detail = format(
          'membership_id=%s user_id=%s email_login=%s email_membership=%s',
          v_membership.id,
          v_membership.user_id,
          coalesce(v_profile_email, 'unknown'),
          v_membership.email
        );
    end if;

    select am.role into v_conflicting_role
    from public.academy_memberships am
    where am.user_id = v_membership.user_id
      and am.id <> v_membership.id
      and am.status = 'active'
      and am.role <> p_new_role
    order by am.updated_at desc, am.id
    limit 1;
    if v_conflicting_role is not null then
      raise exception using
        message = 'ROLE_CONFLICT',
        detail = format('existing_role=%s new_role=%s', v_conflicting_role, p_new_role);
    end if;
  end if;

  if exists (
    select 1
    from private.membership_alias_conflicts mac
    where mac.membership_id = v_membership.id
      and mac.resolved_at is null
  ) then
    raise exception using
      message = 'MEMBERSHIP_OWNERSHIP_CONFLICT',
      detail = format(
        'membership_id=%s user_id=%s email_login=%s email_membership=%s',
        v_membership.id,
        coalesce(v_membership.user_id::text, 'unknown'),
        coalesce(v_profile_email, 'unknown'),
        v_membership.email
      );
  end if;

  if v_membership.role = 'student' and p_new_role = 'teacher' then
    delete from public.class_members cm where cm.membership_id = v_membership.id;
    get diagnostics v_class_memberships = row_count;
    delete from public.student_profiles sp where sp.membership_id = v_membership.id;
    get diagnostics v_student_profiles = row_count;
  end if;

  update public.academy_memberships am
  set role = p_new_role
  where am.id = v_membership.id;

  v_cleaned := jsonb_build_object(
    'student_profiles_archived', v_student_profiles,
    'class_memberships_removed', v_class_memberships
  );

  if v_membership.user_id is not null then
    perform public.reconcile_active_academy_preference(v_membership.user_id);
    select synced.metadata_payload, synced.request_id
    into v_metadata_payload, v_metadata_request_id
    from public.sync_user_metadata(
      v_membership.user_id,
      '[]'::jsonb,
      v_request_id
    ) synced;
  end if;

  insert into private.membership_role_audit (
    membership_id,
    academy_id,
    actor_user_id,
    old_role,
    new_role,
    reason,
    request_id,
    cleaned_records
  ) values (
    v_membership.id,
    v_membership.academy_id,
    p_actor_user_id,
    v_membership.role,
    p_new_role,
    nullif(btrim(coalesce(p_reason, '')), ''),
    v_request_id,
    v_cleaned
  )
  on conflict on constraint membership_role_audit_request_key do nothing;

  membership_id := v_membership.id;
  academy_id := v_membership.academy_id;
  old_role := v_membership.role;
  new_role := p_new_role;
  cleaned_records := v_cleaned;
  metadata_payload := v_metadata_payload;
  should_refresh_session := v_membership.user_id is not null;
  request_id := coalesce(v_metadata_request_id, v_request_id);
  return next;
end;
$$;

create or replace function public.resolve_membership_alias(
  p_actor_user_id uuid,
  p_actor_academy_id bigint,
  p_actor_is_platform_admin boolean,
  p_membership_id bigint,
  p_normalized_email text,
  p_reason text default null,
  p_request_id uuid default gen_random_uuid()
)
returns table (
  membership_id bigint,
  email_normalized text,
  metadata_payload jsonb,
  should_refresh_session boolean,
  request_id uuid
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_membership public.academy_memberships%rowtype;
  v_conflict private.membership_alias_conflicts%rowtype;
  v_email text := lower(btrim(coalesce(p_normalized_email, '')));
  v_request_id uuid := coalesce(p_request_id, gen_random_uuid());
begin
  perform private.assert_service_role();
  if position('@' in v_email) <= 1 then
    raise exception using message = 'EMAIL_MISMATCH';
  end if;

  select * into v_membership
  from public.academy_memberships am
  where am.id = p_membership_id
  for update;
  if v_membership.id is null then
    raise exception using message = 'MEMBERSHIP_NOT_FOUND';
  end if;

  perform private.assert_admin_actor(
    p_actor_user_id,
    p_actor_academy_id,
    coalesce(p_actor_is_platform_admin, false),
    v_membership.academy_id
  );

  select * into v_conflict
  from private.membership_alias_conflicts mac
  where mac.membership_id = v_membership.id
    and mac.resolution_request_id = v_request_id
  order by mac.resolved_at desc, mac.id desc
  limit 1;

  if v_conflict.id is not null
     and v_conflict.email_login = v_email
     and v_membership.email = v_email then
    membership_id := v_membership.id;
    email_normalized := v_email;
    metadata_payload := null;
    should_refresh_session := false;
    request_id := v_request_id;
    return next;
    return;
  end if;
  if v_conflict.id is not null then
    raise exception using message = 'REQUEST_ID_REUSE';
  end if;

  if v_membership.status <> 'awaiting_login' or v_membership.user_id is not null then
    raise exception using message = 'INVALID_MEMBERSHIP_STATUS';
  end if;

  select * into v_conflict
  from private.membership_alias_conflicts mac
  where mac.membership_id = v_membership.id
    and mac.resolved_at is null
  order by mac.detected_at desc, mac.id desc
  limit 1
  for update;

  if v_conflict.id is null or v_conflict.email_login <> v_email then
    raise exception using message = 'EMAIL_MISMATCH';
  end if;

  begin
    update public.academy_memberships am
    set email = v_email
    where am.id = v_membership.id;
  exception
    when unique_violation then
      raise exception using message = 'EMAIL_MISMATCH';
  end;

  update private.membership_alias_conflicts mac
  set resolved_at = clock_timestamp(),
      resolver_id = p_actor_user_id,
      resolution_reason = nullif(btrim(coalesce(p_reason, '')), ''),
      resolution_request_id = v_request_id
  where mac.id = v_conflict.id;

  update private.membership_alias_conflicts mac
  set resolved_at = clock_timestamp(),
      resolver_id = p_actor_user_id,
      resolution_reason = nullif(btrim(coalesce(p_reason, '')), '')
  where mac.membership_id = v_membership.id
    and mac.resolved_at is null
    and mac.id <> v_conflict.id;

  membership_id := v_membership.id;
  email_normalized := v_email;
  metadata_payload := null;
  should_refresh_session := false;
  request_id := v_request_id;
  return next;
end;
$$;

create or replace function public.create_speaking_session(
  p_persona_id bigint,
  p_scenario_id bigint default null,
  p_use_profile boolean default false,
  p_nuances text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_membership public.academy_memberships%rowtype;
  v_session_id uuid;
begin
  select * into v_membership from public.resolve_current_membership(auth.uid());
  if v_membership.id is null
     or v_membership.status <> 'active'
     or v_membership.role <> 'student' then
    raise exception 'Active student membership required';
  end if;
  if not exists (
    select 1 from public.speaking_personas sp where sp.id = p_persona_id and sp.is_active
  ) then
    raise exception 'Persona not available';
  end if;
  if p_scenario_id is not null and not exists (
    select 1 from public.speaking_scenarios ss
    where ss.id = p_scenario_id
      and (
        ss.created_by_membership_id is null
        or ss.created_by_membership_id = v_membership.id
      )
  ) then
    raise exception 'Scenario not accessible';
  end if;

  insert into public.speaking_sessions (
    membership_id, scenario_id, persona_id, use_profile, nuances
  ) values (
    v_membership.id, p_scenario_id, p_persona_id, p_use_profile, nullif(btrim(p_nuances), '')
  ) returning id into v_session_id;
  return v_session_id;
end;
$$;

