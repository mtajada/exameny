begin;

create table if not exists public.academies (
  id bigint generated by default as identity primary key,
  name text not null unique check (btrim(name) <> ''),
  created_at timestamptz not null default now()
);

create table if not exists public.levels (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z][A-Z0-9_]{1,15}$'),
  name text not null check (btrim(name) <> ''),
  created_at timestamptz not null default now()
);

create table if not exists public.exam_types (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z][A-Z0-9_]{1,31}$'),
  name text not null check (btrim(name) <> ''),
  description text,
  max_score integer not null check (max_score > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.evaluation_criteria (
  id bigint generated by default as identity primary key,
  criterion_code text not null unique check (criterion_code ~ '^[A-Z][A-Z0-9_]{1,47}$'),
  name text not null check (btrim(name) <> ''),
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text,
  role text check (role is null or role in ('platform_owner', 'super_admin')),
  academy_id bigint references public.academies(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_email_normalized check (
    email = lower(btrim(email)) and position('@' in email) > 1
  ),
  constraint profiles_full_name_nonblank check (full_name is null or btrim(full_name) <> '')
);

create table if not exists public.academy_memberships (
  id bigint generated by default as identity primary key,
  academy_id bigint not null references public.academies(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null,
  email text not null,
  role text not null check (role in ('student', 'teacher', 'academy_admin')),
  status text not null default 'awaiting_login'
    check (status in ('awaiting_login', 'active', 'inactive')),
  subscription_start_date date,
  subscription_end_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint academy_memberships_email_normalized check (
    email = lower(btrim(email)) and position('@' in email) > 1
  ),
  constraint academy_memberships_academy_email_key unique (academy_id, email),
  constraint academy_memberships_pending_user_check
    check (status <> 'awaiting_login' or user_id is null),
  constraint academy_memberships_claimed_user_check
    check (status = 'awaiting_login' or user_id is not null),
  constraint academy_memberships_date_order_check
    check (
      subscription_start_date is null
      or subscription_end_date is null
      or subscription_end_date >= subscription_start_date
    )
);

create unique index if not exists academy_memberships_academy_user_idx
  on public.academy_memberships (academy_id, user_id)
