      nullif(btrim(v_question ->> 'explanation'), ''),
      nullif(btrim(v_question ->> 'original_sentence'), ''),
      nullif(btrim(v_question ->> 'transformation_sentence'), '')
    ) returning id into v_question_id;

    if jsonb_typeof(v_question -> 'options') = 'array' then
      for v_option in select value from jsonb_array_elements(v_question -> 'options')
      loop
        insert into public.ruoe_options (
          question_id, option_letter, option_text, is_correct, feedback
        ) values (
          v_question_id,
          upper(btrim(v_option ->> 'option_letter')),
          btrim(v_option ->> 'option_text'),
          coalesce((v_option ->> 'is_correct')::boolean, false),
          nullif(btrim(v_option ->> 'feedback'), '')
        );
      end loop;
    end if;
  end loop;

  return v_exercise_id;
