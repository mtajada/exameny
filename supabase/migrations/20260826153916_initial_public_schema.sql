          student_id, task_type_id, writing_submission_id, anchor_text,
          anchor_start, anchor_end, suggested_correction, explanation,
          category_id, tag_id, meta
        ) values (
          v_submission.student_id,
          v_submission.task_type_id,
          p_submission_id,
          coalesce(v_item ->> 'anchor_text', ''),
          greatest(0, coalesce((v_item ->> 'anchor_start')::integer, 0)),
          greatest(1, coalesce((v_item ->> 'anchor_end')::integer, 1)),
          v_item ->> 'suggested_correction',
          coalesce(v_item ->> 'explanation', 'Review this passage.'),
          v_category_id,
          v_tag_id,
          coalesce(v_item -> 'meta', '{}'::jsonb)
        )
        on conflict do nothing;
      end if;
    end loop;
  end if;

  update public.evaluations
  set ai_mistakes_status = 'completed',
      ai_mistakes_summary = jsonb_build_object(
        'count', (select count(*) from public.mistakes where writing_submission_id = p_submission_id)
      )
  where submission_id = p_submission_id;
end;
$$;

create or replace function public.create_speaking_session(
  p_persona_id bigint,
  p_scenario_id bigint default null,
  p_use_profile boolean default false,
  p_nuances text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_membership public.academy_memberships%rowtype;
  v_session_id uuid;
begin
  select * into v_membership from public.resolve_current_membership(auth.uid());
  if v_membership.id is null then
    raise exception 'Active membership required';
  end if;
  if not exists (
    select 1 from public.speaking_personas sp where sp.id = p_persona_id and sp.is_active
  ) then
    raise exception 'Persona not available';
  end if;
  if p_scenario_id is not null and not exists (
    select 1 from public.speaking_scenarios ss
    where ss.id = p_scenario_id
      and (
        ss.created_by_membership_id is null
        or ss.created_by_membership_id = v_membership.id
        or public.can_manage_academy(v_membership.academy_id, auth.uid())
      )
  ) then
    raise exception 'Scenario not accessible';
  end if;

  insert into public.speaking_sessions (
    membership_id, scenario_id, persona_id, use_profile, nuances
  ) values (
    v_membership.id, p_scenario_id, p_persona_id, p_use_profile, nullif(btrim(p_nuances), '')
  ) returning id into v_session_id;
  return v_session_id;
end;
$$;

create or replace function public.save_speaking_transcript(
  p_session_id uuid,
  p_transcript jsonb
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_turn jsonb;
begin
  if not exists (select 1 from public.speaking_sessions where id = p_session_id) then
    raise exception 'Session not found';
  end if;

  insert into public.speaking_transcripts (session_id, full_text, raw_json)
  values (
    p_session_id,
    coalesce(p_transcript ->> 'full_text', p_transcript ->> 'fullText', ''),
    p_transcript
  )
  on conflict (session_id) do update set
    full_text = excluded.full_text,
    raw_json = excluded.raw_json;

  delete from public.speaking_turns where session_id = p_session_id;
  if jsonb_typeof(p_transcript -> 'turns') = 'array' then
    for v_turn in select value from jsonb_array_elements(p_transcript -> 'turns')
    loop
      insert into public.speaking_turns (
        session_id, speaker, start_ms, end_ms, text, filler_count, wpm, raw_json
      ) values (
        p_session_id,
        case when v_turn ->> 'speaker' = 'agent' then 'agent' else 'user' end,
        (v_turn ->> 'start_ms')::integer,
        (v_turn ->> 'end_ms')::integer,
        coalesce(v_turn ->> 'text', ''),
        (v_turn ->> 'filler_count')::integer,
        (v_turn ->> 'wpm')::numeric,
        v_turn
      );
    end loop;
  end if;
  update public.speaking_sessions set status = 'completed' where id = p_session_id;
end;
$$;

