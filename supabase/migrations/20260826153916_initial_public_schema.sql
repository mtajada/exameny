create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at := statement_timestamp();
  return new;
end;
$$;

create or replace function public.student_profiles_sync_user()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_membership public.academy_memberships%rowtype;
begin
  select * into v_membership
  from public.academy_memberships
  where id = new.membership_id;

  if v_membership.id is null
     or v_membership.user_id is null
     or v_membership.role <> 'student' then
    raise exception 'A claimed student membership is required';
  end if;

  new.user_id := v_membership.user_id;
  return new;
end;
$$;

create or replace function public.student_profiles_archive()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.student_profiles_history (
    membership_id, user_id, target_exam_id, target_level_id,
    assigned_teacher_id, created_at, updated_at, archived_at
  ) values (
    old.membership_id, old.user_id, old.target_exam_id, old.target_level_id,
    old.assigned_teacher_id, old.created_at, old.updated_at, clock_timestamp()
  );
  if tg_op = 'UPDATE' then
    return new;
  end if;
  return old;
end;
$$;

