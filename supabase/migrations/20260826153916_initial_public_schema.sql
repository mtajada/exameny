  v_option jsonb;
  v_question_id bigint;
  v_order integer;
  v_answers text[];
begin
  if not public.can_manage_academy(p_academy_id, auth.uid())
     and coalesce(auth.jwt() ->> 'role', '') <> 'service_role' then
    raise exception 'Not authorized';
