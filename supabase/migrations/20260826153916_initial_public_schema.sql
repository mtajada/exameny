create or replace function public.start_ruoe_attempt(
  p_exercise_id bigint,
  p_retry_from_attempt_id bigint default null
)
returns public.ruoe_user_attempts
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_membership public.academy_memberships%rowtype;
  v_exercise public.ruoe_exercises%rowtype;
  v_attempt public.ruoe_user_attempts%rowtype;
  v_next_number integer;
begin
  select * into v_membership from public.resolve_current_membership(auth.uid());
  select * into v_exercise from public.ruoe_exercises where id = p_exercise_id;
  if v_membership.id is null or v_membership.role <> 'student' then
    raise exception 'Active student membership required';
  end if;
  if v_exercise.id is null
     or (not v_exercise.is_public and v_exercise.academy_id <> v_membership.academy_id) then
    raise exception 'Exercise not accessible';
  end if;
  if exists (
    select 1 from public.ruoe_user_attempts rua
    where rua.membership_id = v_membership.id
      and rua.exercise_id = p_exercise_id
      and rua.status = 'in_progress'
  ) then
    select * into v_attempt
    from public.ruoe_user_attempts rua
    where rua.membership_id = v_membership.id
      and rua.exercise_id = p_exercise_id
      and rua.status = 'in_progress';
    return v_attempt;
  end if;
  if p_retry_from_attempt_id is not null and not exists (
    select 1 from public.ruoe_user_attempts rua
    where rua.id = p_retry_from_attempt_id
      and rua.membership_id = v_membership.id
      and rua.exercise_id = p_exercise_id
      and rua.status = 'completed'
  ) then
    raise exception 'Retry source is invalid';
  end if;

  select coalesce(max(rua.attempt_number), 0) + 1 into v_next_number
  from public.ruoe_user_attempts rua
  where rua.membership_id = v_membership.id and rua.exercise_id = p_exercise_id;

  insert into public.ruoe_user_attempts (
    membership_id, student_id, exercise_id, attempt_number, restarted_from_attempt_id
  ) values (
    v_membership.id, auth.uid(), p_exercise_id, v_next_number, p_retry_from_attempt_id
  ) returning * into v_attempt;
  return v_attempt;
end;
$$;

create or replace function public.evaluate_ruoe_attempt(p_attempt_id bigint)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_attempt public.ruoe_user_attempts%rowtype;
  v_total integer;
  v_correct integer;
  v_score numeric(7, 2);
begin
  select * into v_attempt
  from public.ruoe_user_attempts rua
  where rua.id = p_attempt_id
  for update;
  if v_attempt.id is null
     or not public.can_access_membership(v_attempt.membership_id, auth.uid()) then
    raise exception 'Attempt not accessible';
  end if;

  update public.ruoe_user_answers a
  set is_correct = exists (
    select 1
    from public.ruoe_questions q
    where q.id = a.question_id
      and (
        lower(btrim(coalesce(a.user_answer, ''))) = any (
          select lower(btrim(answer)) from unnest(q.correct_answers) answer
        )
        or exists (
          select 1 from public.ruoe_options o
          where o.question_id = q.id
            and o.is_correct
            and upper(btrim(coalesce(a.user_answer, ''))) = o.option_letter
        )
      )
  )
  where a.attempt_id = p_attempt_id;

  select count(*), count(*) filter (where a.is_correct)
  into v_total, v_correct
  from public.ruoe_user_answers a
  where a.attempt_id = p_attempt_id;
  v_score := case when v_total = 0 then 0 else round((v_correct::numeric / v_total) * 100, 2) end;

  update public.ruoe_user_attempts
  set status = 'completed', score = v_score, max_score = 100, completed_at = statement_timestamp()
  where id = p_attempt_id;

  return jsonb_build_object(
    'attemptId', p_attempt_id,
    'correctCount', v_correct,
    'questionCount', v_total,
    'scorePoints', v_score,
    'maxScorePoints', 100,
    'status', 'completed'
  );
end;
$$;

