create or replace function public.sync_user_metadata(
  p_user_id uuid,
  p_memberships_claimed jsonb default '[]'::jsonb,
  p_request_id uuid default gen_random_uuid()
)
returns table (
  metadata_payload jsonb,
  request_id uuid,
  should_refresh_session boolean
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_profile public.profiles%rowtype;
  v_memberships jsonb;
  v_active public.academy_memberships%rowtype;
begin
  if p_user_id is distinct from auth.uid()
     and current_user not in ('postgres', 'service_role')
     and coalesce(auth.jwt() ->> 'role', '') <> 'service_role' then
    raise exception 'Not authorized';
  end if;

  select * into v_profile from public.profiles where id = p_user_id;
  select * into v_active from public.resolve_current_membership(p_user_id);

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'membership_id', am.id,
        'academy_id', am.academy_id,
        'role', am.role,
        'status', am.status
      ) order by am.academy_id
    ),
    '[]'::jsonb
  ) into v_memberships
  from public.academy_memberships am
  where am.user_id = p_user_id;

  metadata_payload := jsonb_build_object(
    'app_metadata', jsonb_strip_nulls(jsonb_build_object(
      'platform_role', v_profile.role,
      'active_academy_id', v_active.academy_id,
      'active_membership_id', v_active.id,
      'active_role', v_active.role,
      'memberships', v_memberships
    )),
    'user_metadata', jsonb_build_object(
      'full_name', coalesce(
        (select up.full_name from public.user_preferences up where up.user_id = p_user_id),
        v_profile.full_name
      )
    ),
    'memberships_claimed', coalesce(p_memberships_claimed, '[]'::jsonb)
  );
  request_id := coalesce(p_request_id, gen_random_uuid());
  should_refresh_session := true;
  return next;
end;
$$;

create or replace function public.process_membership_claim(
  p_membership_id bigint,
  p_user_id uuid,
  p_force_status_active boolean default true
)
returns public.academy_memberships
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_membership public.academy_memberships%rowtype;
begin
  select * into v_membership
  from public.academy_memberships
  where id = p_membership_id
  for update;

  if v_membership.id is null or v_membership.status <> 'awaiting_login' then
    raise exception 'Pending membership not found';
  end if;

  update public.academy_memberships
  set user_id = p_user_id,
      status = case when p_force_status_active then 'active' else 'inactive' end
  where id = p_membership_id
  returning * into v_membership;

  return v_membership;
end;
$$;

create or replace function public.reconcile_active_academy_preference(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_academy_id bigint;
begin
  select am.academy_id into v_academy_id
  from public.academy_memberships am
  where am.user_id = p_user_id and am.status = 'active'
  order by am.updated_at desc, am.id
  limit 1;

  insert into public.user_preferences (user_id, active_academy_id)
  values (p_user_id, v_academy_id)
  on conflict (user_id) do update
    set active_academy_id = case
      when exists (
        select 1 from public.academy_memberships am
        where am.user_id = p_user_id
          and am.academy_id = public.user_preferences.active_academy_id
          and am.status = 'active'
      ) then public.user_preferences.active_academy_id
      else excluded.active_academy_id
    end;
end;
$$;

create or replace function public.finalize_invited_signup(
  p_request_id uuid default gen_random_uuid()
)
returns table (
  auto_selected_academy_id bigint,
  is_platform_admin boolean,
  memberships jsonb,
  memberships_claimed jsonb,
  memberships_inactive jsonb,
  metadata_payload jsonb,
  request_id uuid,
  should_refresh_session boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_email text := public.get_my_email_from_jwt();
  v_claimed jsonb := '[]'::jsonb;
  v_metadata record;
begin
  if v_user_id is null or v_email = '' then
    raise exception 'Authenticated user and email are required';
  end if;

  insert into public.profiles (id, email)
  values (v_user_id, v_email)
  on conflict (id) do update set email = excluded.email;

  with claimed as (
    update public.academy_memberships am
    set user_id = v_user_id, status = 'active'
    where am.email = v_email
      and am.status = 'awaiting_login'
      and am.user_id is null
    returning am.id, am.academy_id, am.role, am.status
  )
  select coalesce(jsonb_agg(to_jsonb(claimed)), '[]'::jsonb)
  into v_claimed
  from claimed;

  if not exists (
    select 1 from public.academy_memberships am where am.user_id = v_user_id
  ) and not public.is_platform_admin(v_user_id) then
    raise exception 'No invitation found';
  end if;

  perform public.reconcile_active_academy_preference(v_user_id);

  select * into v_metadata
  from public.sync_user_metadata(v_user_id, v_claimed, p_request_id);

  auto_selected_academy_id := (
    select up.active_academy_id from public.user_preferences up where up.user_id = v_user_id
  );
  is_platform_admin := public.is_platform_admin(v_user_id);
  select coalesce(jsonb_agg(to_jsonb(am) order by am.academy_id), '[]'::jsonb)
    into memberships
  from public.academy_memberships am
  where am.user_id = v_user_id and am.status = 'active';
  memberships_claimed := v_claimed;
  select coalesce(jsonb_agg(to_jsonb(am) order by am.academy_id), '[]'::jsonb)
    into memberships_inactive
  from public.academy_memberships am
  where am.user_id = v_user_id and am.status = 'inactive';
  metadata_payload := v_metadata.metadata_payload;
  request_id := v_metadata.request_id;
  should_refresh_session := v_metadata.should_refresh_session;
  return next;
end;
$$;

